-- 加工種別マスタ（process_types）の番号の振り直し、レーザー孔とプラズマ孔の統合、「入力の形」の設定。
--
-- 前提: マイグレーション 20261002100000_add_process_input_shapes.sql と seed 004 が適用済みであること。
--
-- 番号は加工の順番に合わせる（docs/table-design.md「process_types」）。
--   10 番台: 切断機で行う加工
--     11 レーザー・プラズマ孔 / 12 ガス孔 / 13 中抜き / 14 長孔 / 15 ピアス孔 / 16 マーキング / 17 切り込み
--   20 番台: 二次加工（工程順。曲げは曲げた後にほかの加工ができないため最後）
--     20 キリ孔 / 21 タップ孔 / 22 ショット / 23 開先 / 24 曲げ
--
-- レーザー孔とプラズマ孔は単価が同じため 1 つにまとめる。
--   ・レーザー孔の行の名前を「レーザー・プラズマ孔」に変えて残す
--   ・プラズマ孔の行は受注から参照されている可能性があるため削除せず、無効にして番号を空にする
--
-- 入力の形（受注登録画面の加工の項目の入力欄。docs/basic-design.md「加工の入力項目」）
--   穴  : 11 レーザー・プラズマ孔 / 12 ガス孔 / 20 キリ孔
--   曲げ: 24 曲げ
--   それ以外は自由入力（形は今後 1 つずつ追加する）
--
-- 番号には一意制約があるため、いったん対象の行の番号をすべて空にしてから振り直す
-- （新しい番号を 1 行ずつ入れると、まだ古い番号を持っている別の行とぶつかる。例: キリ孔 11 → 20 の前に
-- レーザー・プラズマ孔に 11 を入れられない）。番号の NULL は一意制約の対象外なので、何行あってもよい。
-- 途中で失敗したときに番号が空のまま残らないよう、全体を 1 つの transaction で実行する。
-- 何度実行しても結果が変わらないように書いている。

begin;

-- 0. 振り直す番号を、この一覧にない加工種別（マスタ画面から追加した行など）が使っていないか確かめる。
--    使っていれば一意制約にぶつかるため、どの行かを示して中止する（その行の番号を変えてから実行し直す）
do $$
declare
  v_conflict text;
begin
  select string_agg(number || ' ' || name, '、' order by number) into v_conflict
  from public.process_types
  where number in (11, 12, 13, 14, 15, 16, 17, 20, 21, 22, 23, 24)
    and name not in (
      'レーザー・プラズマ孔', 'ガス孔', '中抜き', '長孔', 'ピアス孔', 'マーキング', '切り込み',
      'キリ孔', 'タップ孔', 'ショット', '開先', '曲げ',
      -- 統合する前の名前
      'レーザー孔', 'プラズマ孔'
    );
  if v_conflict is not null then
    raise exception '振り直す番号をほかの加工種別が使っています: %', v_conflict;
  end if;
end
$$;

-- 1. 対象の行の番号をいったん空にする
update public.process_types
set number = null
where name in (
  'レーザー・プラズマ孔', 'ガス孔', '中抜き', '長孔', 'ピアス孔', 'マーキング', '切り込み',
  'キリ孔', 'タップ孔', 'ショット', '開先', '曲げ',
  'レーザー孔', 'プラズマ孔'
);

-- 2. レーザー孔の行を「レーザー・プラズマ孔」に変える（統合済みなら何もしない）
update public.process_types
set name = 'レーザー・プラズマ孔'
where name = 'レーザー孔'
  and not exists (select 1 from public.process_types where name = 'レーザー・プラズマ孔');

-- 3. プラズマ孔の行は無効にする（番号は 1 で空にしてある。受注から参照されている可能性があるため削除しない）
update public.process_types
set is_active = false
where name = 'プラズマ孔';

-- 4. 新しい番号と入力の形を付ける
--    （with 句は 1 つの文の中でしか使えないため、5 にも同じ一覧を書いている）
with v(number, name, input_shape) as (values
  (11, 'レーザー・プラズマ孔', '穴'),
  (12, 'ガス孔', '穴'),
  (13, '中抜き', '自由入力'),
  (14, '長孔', '自由入力'),
  (15, 'ピアス孔', '自由入力'),
  (16, 'マーキング', '自由入力'),
  (17, '切り込み', '自由入力'),
  (20, 'キリ孔', '穴'),
  (21, 'タップ孔', '自由入力'),
  (22, 'ショット', '自由入力'),
  (23, '開先', '自由入力'),
  (24, '曲げ', '曲げ')
)
update public.process_types as t
set number = v.number,
    input_shape = v.input_shape
from v
where t.name = v.name;

-- 5. まだない加工種別（ガス孔など）を追加する
with v(number, name, input_shape) as (values
  (11, 'レーザー・プラズマ孔', '穴'),
  (12, 'ガス孔', '穴'),
  (13, '中抜き', '自由入力'),
  (14, '長孔', '自由入力'),
  (15, 'ピアス孔', '自由入力'),
  (16, 'マーキング', '自由入力'),
  (17, '切り込み', '自由入力'),
  (20, 'キリ孔', '穴'),
  (21, 'タップ孔', '自由入力'),
  (22, 'ショット', '自由入力'),
  (23, '開先', '自由入力'),
  (24, '曲げ', '曲げ')
)
insert into public.process_types (number, name, input_shape)
select v.number, v.name, v.input_shape
from v
where not exists (select 1 from public.process_types as t where t.name = v.name);

commit;
