-- 材質の初期値に関する変更。
--
--   1. SS400 の番号を 0 にする（ほかの材質の番号は変えない。1 は空き番号になる）
--   2. 材質ごとに製鋼法の初期値（default_steel_making）を持たせる
--
-- 受注登録画面の番号入力では、「0 はいつもの値（初期値）」とする考え方にそろえる
-- （種類 0 普通板・メーカー 0 指定なし と同じ。docs/screen-design.md「番号の一覧」）。
-- 最も多く使う SS400 を 0 にし、明細の材質の欄に最初から入れておくことで、Enter だけで進めるようにする。
--
-- 製鋼法は材質によって決まることが多いため（SS400 は電炉材、それ以外の規格材は高炉材が多い）、
-- 材質を選んだときに製鋼法をその材質の初期値にする。初期値はそのあと画面で変更できる。


-- ============================================================
-- 1. SS400 の番号を 0 にする
-- ============================================================
-- 番号の一意制約（materials_number_key）があるため、0 がほかの材質で使われていないことが前提。
-- 使われている場合は一意制約の違反でこのマイグレーションが失敗する（先にマスタ画面で番号を直すこと）。
update public.materials set number = 0 where name = 'SS400';


-- ============================================================
-- 2. 製鋼法の初期値
-- ============================================================
-- 値域は order_items.steel_making と同じ（電炉材 / 高炉材）。
-- 既定値は電炉材とし、下の対応表にない材質（画面から追加された材質など）は電炉材のままにする。
alter table public.materials
  add column default_steel_making text not null default '電炉材'
    check (default_steel_making in ('電炉材', '高炉材'));

comment on column public.materials.default_steel_making is
  '受注明細で材質を選んだときに入れる製鋼法の初期値（電炉材 / 高炉材）。画面で変更できる。';

update public.materials
set default_steel_making = '高炉材'
where name in (
  'SN400B', 'SM490A', 'SN490B', 'SN490C',
  'SN400C', 'SM400A', 'TMCP325C', 'TMCP385C'
);
